FONT = '<w:rFonts w:ascii="Times New Roman" w:hAnsi="Times New Roman" w:eastAsia="宋体" w:cs="Times New Roman"/>'
FONT_H = '<w:rFonts w:ascii="Times New Roman" w:hAnsi="Times New Roman" w:eastAsia="宋体" w:cs="Times New Roman" w:hint="eastAsia"/>'


def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def run(text, bold=False):
    b = "<w:b/><w:bCs/>" if bold else ""
    return ('<w:r><w:rPr>' + FONT_H + b + '</w:rPr><w:t xml:space="preserve">'
            + esc(text) + '</w:t></w:r>')


def run_mono(text, bold=False):
    """代码/文件名用等宽字体（Consolas），中文仍走宋体"""
    b = "<w:b/><w:bCs/>" if bold else ""
    f = ('<w:rFonts w:ascii="Consolas" w:hAnsi="Consolas" w:eastAsia="宋体" '
         'w:cs="Consolas" w:hint="eastAsia"/>')
    return ('<w:r><w:rPr>' + f + b + '</w:rPr><w:t xml:space="preserve">'
            + esc(text) + '</w:t></w:r>')


INLINE_BOLD = re.compile(r'\*\*(.+?)\*\*', re.S)
INLINE_CODE = re.compile(r'`([^`]+)`')


def inline_runs(text, bold=False):
    """把行内标记渲染成真正的 Word 格式：**粗体** -> 加粗，`code` -> 等宽。
    避免 **、` 这类 Markdown 残留直接出现在报告正文里。"""
    out = []
    tokens = []
    pos = 0
    for m in INLINE_BOLD.finditer(text):
        if m.start() > pos:
            tokens.append((text[pos:m.start()], bold))
        tokens.append((m.group(1), True))
        pos = m.end()
    if pos < len(text):
        tokens.append((text[pos:], bold))
    for seg, is_bold in tokens:
        p2 = 0
        for m in INLINE_CODE.finditer(seg):
            if m.start() > p2:
                out.append(run(seg[p2:m.start()], is_bold))
            out.append(run_mono(m.group(1), is_bold))
            p2 = m.end()
        if p2 < len(seg):
            out.append(run(seg[p2:], is_bold))
    return ''.join(out)


def para(text, bold=False, indent=True):
    """正文段落：完全沿用模板里正文段落的格式（样式 12 + 缩进 + 宋体）"""
    ind = '<w:ind w:left="420" w:firstLine="0" w:firstLineChars="0"/>' if indent else '<w:ind w:firstLine="0" w:firstLineChars="0"/>'
    return ('<w:p><w:pPr><w:pStyle w:val="12"/><w:spacing w:line="360" w:lineRule="auto"/>'
            + ind + '<w:rPr>' + FONT + '</w:rPr></w:pPr>' + inline_runs(text, bold) + '</w:p>')


def blank():
    return ('<w:p><w:pPr><w:pStyle w:val="12"/><w:spacing w:line="360" w:lineRule="auto"/>'
            '<w:ind w:left="420" w:firstLine="0" w:firstLineChars="0"/><w:rPr>' + FONT + '</w:rPr></w:pPr></w:p>')


def sub(title):
    """小标题：加粗，无缩进"""
    return para(title, bold=True, indent=False)


def table(rows, widths=None):
    """构造带边框的表格；第一行为表头（浅底纹）"""
    ncol = max(len(r) for r in rows)
    if widths is None:
        widths = [int(9526 / ncol)] * ncol
    x = ['<w:tbl><w:tblPr><w:tblW w:type="pct" w:w="5000"/><w:jc w:val="center"/><w:tblBorders>']
    for sd in ("top", "left", "bottom", "right", "insideH", "insideV"):
        x.append('<w:' + sd + ' w:val="single" w:sz="4" w:space="0" w:color="808080"/>')
    x.append('</w:tblBorders><w:tblCellMar>'
             '<w:top w:w="40" w:type="dxa"/><w:left w:w="80" w:type="dxa"/>'
             '<w:bottom w:w="40" w:type="dxa"/><w:right w:w="80" w:type="dxa"/></w:tblCellMar></w:tblPr><w:tblGrid>')
    for w in widths:
        x.append('<w:gridCol w:w="%d"/>' % w)
    x.append('</w:tblGrid>')
    for ri, r in enumerate(rows):
        x.append('<w:tr>')
        if ri == 0:
            x.append('<w:trPr><w:tblHeader/></w:trPr>')
        for ci in range(ncol):
            cell = r[ci] if ci < len(r) else ""
            shd = '<w:shd w:val="clear" w:color="auto" w:fill="DCE6F2"/>' if ri == 0 else ''
            x.append('<w:tc><w:tcPr><w:tcW w:type="dxa" w:w="%d"/>%s</w:tcPr>' % (widths[ci], shd))
            x.append('<w:p><w:pPr><w:spacing w:line="300" w:lineRule="auto"/>'
                     '<w:jc w:val="left"/><w:rPr>' + FONT + '</w:rPr></w:pPr>'
                     + run(cell, bold=(ri == 0)) + '</w:p></w:tc>')
        x.append('</w:tr>')
    x.append('</w:tbl>')
    return "".join(x)


