def table(rows, widths=None):
    """构造带边框的表格；第一行为表头（浅底纹）"""
    ncol = max(len(r) for r in rows)
    if widths is None:
        widths = [int(9526 / ncol)] * ncol
    x = ['<w:tbl><w:tblPr><w:tblW w:type="pct" w:w="5000"/><w:jc w:val="center"/><w:tblBorders>']
    for sd in ("top", "left", "bottom", "right", "insideH", "insideV"):
        x.append('<w:' + sd + ' w:val="single" w:sz="4" w:space="0" w:color="808080"/>')
    x.append('</w:tblBorders><w:tblCellMar>'
             '<w:top w:w="40" w:type="dxa"/><w:left w:w="80" w:type="dxa"/>'
             '<w:bottom w:w="40" w:type="dxa"/><w:right w:w="80" w:type="dxa"/></w:tblCellMar></w:tblPr><w:tblGrid>')
    for w in widths:
        x.append('<w:gridCol w:w="%d"/>' % w)
    x.append('</w:tblGrid>')
    for ri, r in enumerate(rows):
        x.append('<w:tr>')
        if ri == 0:
            x.append('<w:trPr><w:tblHeader/></w:trPr>')
        for ci in range(ncol):
            cell = r[ci] if ci < len(r) else ""
            shd = '<w:shd w:val="clear" w:color="auto" w:fill="DCE6F2"/>' if ri == 0 else ''
            x.append('<w:tc><w:tcPr><w:tcW w:type="dxa" w:w="%d"/>%s</w:tcPr>' % (widths[ci], shd))
            x.append('<w:p><w:pPr><w:spacing w:line="300" w:lineRule="auto"/>'
                     '<w:jc w:val="left"/><w:rPr>' + FONT + '</w:rPr></w:pPr>'
                     + run(cell, bold=(ri == 0)) + '</w:p></w:tc>')
        x.append('</w:tr>')
    x.append('</w:tbl>')
    return "".join(x)


