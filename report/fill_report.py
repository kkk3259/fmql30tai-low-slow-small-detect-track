HINT_RE = re.compile(r"^(（不要出现任何涉及学校名称等内容）|\d+字内.*|\d+字以内.*|按照标准格式.*|2\.3\.[12] .*；)$")

def main():
    zin = zipfile.ZipFile(TPL)
    doc = zin.read("word/document.xml").decode("utf-8")

    # 定位 body：必须保留 <w:body> 之前的全部内容（XML 声明 + w:document 根元素声明）
    i_body = doc.find("<w:body>") + len("<w:body>")
    pre = doc[:i_body]                                   # <?xml?> + <w:document xmlns...> + <w:body>
    m = re.match(r"(.*?)(<w:sectPr\b.*)$", doc[i_body:], re.S)
    inner, post = m.group(1), m.group(2)                 # post = <w:sectPr...>...</w:body></w:document>

    paras = re.findall(r"<w:p\b(?:(?!<w:p\b).)*?</w:p>", inner, re.S)
    other_before = inner[:inner.find(paras[0])] if paras else inner

    def text_of(p):
        t = "".join(re.findall(r"<w:t(?:\s[^>]*)?>(.*?)</w:t>", p, re.S))
        return (t.replace("&amp;", "&").replace("&lt;", "<").replace("&gt;", ">")
                 .replace("&quot;", '"').replace("&apos;", "'"))

    out = [other_before]
    filled = []
    for p in paras:
        t = text_of(p).strip()
        if HINT_RE.match(t):
            continue                      # 删除提示行
        out.append(p)                     # 保留原段落（含样式与编号）
        if t in FILL:
            for kind, payload in FILL[t]:
                if kind == "NAME":
                    out.append(para(payload, bold=True, indent=False))
                elif kind == "S":
                    out.append(sub(payload))
                elif kind == "A":
                    for line in payload:
                        out.append(para(line))
                elif kind == "T":
                    out.append(table(payload))
                out.append(blank())
            filled.append(t)

    new_doc = pre + "".join(out) + post

    # 打包：复制模板全部部件，只替换 document.xml
    for f in (OUT, OUT + ".new"):
        if os.path.exists(f):
            os.remove(f)
    tmp = OUT + ".new"
